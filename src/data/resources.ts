export const RESOURCE_BY_ID: Record<string, Resource> = Object.fromEntries(
  RESOURCES.map((r) => [r.id, r])
);

export const resourcesOfSection = (section: SectionId): Resource[] =>
  RESOURCES.filter((r) => r.section === section);

export function groupsOfSection(section: SectionId): { group: string; items: Resource[] }[] {
  const out: { group: string; items: Resource[] }[] = [];
  for (const r of resourcesOfSection(section)) {
    const last = out.find((g) => g.group === r.group);
    if (last) last.items.push(r);
    else out.push({ group: r.group, items: [r] });
  }
  return out;
}

